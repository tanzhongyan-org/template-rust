#!/usr/bin/env node
// Generates or checks NOTICE, the third-party crate list.
// Usage: node scripts/licenses.mjs [--write]
// Without --write, exits 1 when NOTICE differs from what cargo metadata says.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const NOTICE = "NOTICE";
const write = process.argv.includes("--write");

const meta = JSON.parse(
  execFileSync("cargo", ["metadata", "--format-version", "1"], {
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  }),
);
const members = new Set(meta.workspace_members);
const rows = meta.packages
  .filter((p) => !members.has(p.id))
  .map((p) => ({
    name: p.name,
    version: p.version,
    license: p.license ?? "Unknown",
    repository: p.repository ?? "",
  }))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

let out =
  "Third-party crates in this repository's dependency closure.\n\n" +
  "Generated by `node scripts/licenses.mjs --write`. Do not edit by hand.\n\n";
for (const r of rows) {
  out += `- ${r.name} ${r.version} (${r.license})${r.repository ? ` ${r.repository}` : ""}\n`;
}

const current = existsSync(NOTICE) ? readFileSync(NOTICE, "utf8") : null;
if (current === out) {
  console.log(`licenses: ${NOTICE} is current (${rows.length} crates)`);
  process.exit(0);
}
if (!write) {
  console.error(
    `licenses: ${NOTICE} is stale. Run \`node scripts/licenses.mjs --write\`, review the diff and commit it.`,
  );
  process.exit(1);
}
writeFileSync(NOTICE, out);
console.log(`licenses: wrote ${NOTICE} (${rows.length} crates)`);
